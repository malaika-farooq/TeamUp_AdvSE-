import { createServerFn } from "@tanstack/react-start";
import { requireSupabaseAuth } from "@/integrations/supabase/auth-middleware";

const SAMPLE_TEAM_NAME = "Sample — CS201 Group Project";

function addDays(days: number, hour = 17) {
  const d = new Date();
  d.setDate(d.getDate() + days);
  d.setHours(hour, 0, 0, 0);
  return d.toISOString();
}

export const createSampleWorkspace = createServerFn({ method: "POST" })
  .middleware([requireSupabaseAuth])
  .handler(async ({ context }) => {
    const supabase = context.supabase;
    const uid = context.userId;

    const existing = await supabase
      .from("teams")
      .select("id")
      .eq("name", SAMPLE_TEAM_NAME)
      .eq("created_by", uid)
      .maybeSingle();
    if (existing.data) return { teamId: existing.data.id, created: false };

    const course = await supabase
      .from("courses")
      .upsert({ code: "CS201", title: "Data Structures" }, { onConflict: "code,title" })
      .select("id")
      .single();

    const { data: teamId, error: teamErr } = await supabase.rpc("create_team", {
      _name: SAMPLE_TEAM_NAME,
      _description: "A demo workspace generated by TeamUp so you can explore every feature.",
      _course_id: course.data?.id ?? null,
      _project_goal: "Ship a working data-structures visualiser and a 12-page report.",
      _deadline: String(addDays(21)).slice(0, 10),
      _visibility: "private",
      _accent: "teal",
    } as never);
    if (teamErr || !teamId) throw new Error(teamErr?.message ?? "Could not create sample team");

    await supabase.from("teams").update({ is_sample: true }).eq("id", teamId);

    const tasks = [
      { title: "Agree on project scope", status: "done", priority: "high", due: addDays(-6) },
      { title: "Collect reference papers", status: "done", priority: "medium", due: addDays(-3) },
      {
        title: "Build the tree visualiser",
        status: "in_progress",
        priority: "urgent",
        due: addDays(4),
      },
      {
        title: "Write methodology section",
        status: "in_progress",
        priority: "high",
        due: addDays(6),
      },
      { title: "Peer review the draft", status: "in_review", priority: "medium", due: addDays(9) },
      { title: "Prepare demo slides", status: "todo", priority: "medium", due: addDays(12) },
      { title: "Rehearse presentation", status: "todo", priority: "low", due: addDays(15) },
      { title: "Submit final report", status: "todo", priority: "urgent", due: addDays(-1) },
    ] as const;

    await supabase.from("tasks").insert(
      tasks.map((t, i) => ({
        team_id: teamId,
        title: t.title,
        description: "Sample task created with your demo workspace.",
        status: t.status,
        priority: t.priority,
        due_date: t.due,
        assignee_id: uid,
        created_by: uid,
        position: (i + 1) * 100,
        completed_at: t.status === "done" ? addDays(-2) : null,
      })),
    );

    const { data: sessions } = await supabase
      .from("sessions")
      .insert([
        {
          team_id: teamId,
          title: "Weekly sync",
          description: "Check progress and unblock each other.",
          starts_at: addDays(2, 16),
          ends_at: addDays(2, 17),
          location: "Library room 3B",
          recurrence: "weekly",
          recurrence_end: addDays(28).slice(0, 10),
          created_by: uid,
        },
        {
          team_id: teamId,
          title: "Report writing sprint",
          starts_at: addDays(5, 13),
          ends_at: addDays(5, 16),
          meeting_link: "https://meet.example.com/studysync-demo",
          created_by: uid,
        },
      ])
      .select("id");

    if (sessions?.length) {
      await supabase
        .from("session_attendees")
        .insert(sessions.map((s) => ({ session_id: s.id, user_id: uid, status: "accepted" })));
    }

    await supabase.from("resources").insert([
      {
        team_id: teamId,
        kind: "note",
        title: "Kickoff meeting notes",
        content:
          "## Decisions\n- Scope locked to AVL + red-black trees\n- Report due in 3 weeks\n\n## Next steps\n- Draft methodology\n- Book the lab room",
        tags: ["meeting", "decisions"],
        created_by: uid,
      },
      {
        team_id: teamId,
        kind: "link",
        title: "Visualising balanced trees (reference)",
        url: "https://en.wikipedia.org/wiki/AVL_tree",
        tags: ["reference"],
        created_by: uid,
      },
    ]);

    await supabase.from("activity_logs").insert([
      { team_id: teamId, actor_id: uid, action: "task_created", summary: "added 8 sample tasks" },
      {
        team_id: teamId,
        actor_id: uid,
        action: "session_created",
        summary: "scheduled a weekly sync",
      },
      { team_id: teamId, actor_id: uid, action: "resource_added", summary: "shared kickoff notes" },
    ]);

    await supabase.from("notifications").insert({
      user_id: uid,
      type: "sample",
      title: "Sample workspace ready",
      body: "Explore the demo team, then remove it whenever you like.",
      link: `/teams/${teamId}`,
    });

    return { teamId, created: true };
  });

export const removeSampleWorkspace = createServerFn({ method: "POST" })
  .middleware([requireSupabaseAuth])
  .handler(async ({ context }) => {
    const { error } = await context.supabase
      .from("teams")
      .delete()
      .eq("created_by", context.userId)
      .eq("is_sample", true);
    if (error) throw new Error(error.message);
    return { ok: true };
  });
